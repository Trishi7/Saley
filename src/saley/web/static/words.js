// A12: the singular template for exactly 1 ("1 story"), else the plural one ("2 stories").
window.fmtCount = function (one, many, n, values) {
  return window.fmt(n === 1 ? one : many, Object.assign({ n: n }, values || {}));
};

window.fmt = function (template, values) {
  return String(template).replace(/\{(\w+)\}/g, function (all, key) {
    return values && values[key] != null ? String(values[key]) : all;
  });
};
